export function translateSectorLabel(value: string | undefined | null, lang: AppLanguage): string {
  const raw = (value || '').trim();
  if (!raw) return lang === 'en' ? 'Tantawy Catalog' : 'كتالوج دريم';
  if (lang === 'ar') return raw;
  return SECTOR_EN_MAP[raw] || raw;
}

export function translateSubcategoryLabel(value: string | undefined | null, lang: AppLanguage): string {
  const raw = (value || '').trim();
  if (!raw) return '';
  if (lang === 'ar') return raw;
  return SUBCATEGORY_EN_MAP[raw] || raw;
}

export function getLocalizedProductName(
  p: Pick<Product, 'name' | 'nameAr'>,
  lang: AppLanguage
): string {
  if (lang === 'en') {
    return (p.name && p.name.trim()) || p.nameAr || '';
  }
  return (p.nameAr && p.nameAr.trim()) || p.name || '';
}

export function getLocalizedProductCategory(
  p: Pick<Product, 'category' | 'categoryAr' | 'sector' | 'itemGroup'>,
  lang: AppLanguage
): string {
  if (lang === 'en') {
    const raw = (p.itemGroup || p.sector || p.category || p.categoryAr || '').trim();
    return translateSubcategoryLabel(raw, 'en') || translateSectorLabel(raw, 'en') || raw;
  }
  return p.itemGroup || p.sector || p.categoryAr || p.category || 'كتالوج دريم';
}

