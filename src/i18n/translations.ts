export function getLocalizedCategoryDesc(
  c: Pick<CategoryItem, 'name' | 'nameAr' | 'descriptionAr'> & { description?: string },
  lang: AppLanguage
): string {
  if (lang === 'en') {
    if (c.description && c.description.trim()) return c.description.trim();
    if (c.nameAr === 'أجهزة منزلية' || c.name.toLowerCase().includes('home')) {
      return 'Cookware, serving trays, glassware, cutlery, dinnerware, and complete kitchenware sets.';
    }
    if (c.nameAr === 'أجهزة كهربيه' || c.name.toLowerCase().includes('electric')) {
      return 'Refrigerators, deep freezers, washing machines, cookers, smart TVs, air conditioners, and small kitchen appliances.';
    }
    return c.descriptionAr || '';
  }
  return (c.descriptionAr && c.descriptionAr.trim()) || c.description || '';
}

